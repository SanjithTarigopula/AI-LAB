import random

def print_board(board):
    for row in board:
        print(row)

def check_winner(board, symbol):
    # Check rows, columns, diagonals
    for i in range(3):
        if all(board[i][j] == symbol for j in range(3)): return True
        if all(board[j][i] == symbol for j in range(3)): return True
    if all(board[i][i] == symbol for i in range(3)): return True
    if all(board[i][2-i] == symbol for i in range(3)): return True
    return False

def is_full(board):
    return all(board[i][j] != " " for i in range(3) for j in range(3))

def tic_tac_toe():
    board = [[" "]*3 for _ in range(3)]
    human, computer = "X", "O"

    while True:
        print_board(board)
        # Human move
        r, c = map(int, input("Enter row and col (0-2): ").split())
        if board[r][c] == " ":
            board[r][c] = human
        else:
            print("Invalid move, try again.")
            continue

        if check_winner(board, human):
            print_board(board)
            print("Human wins!")
            break
        if is_full(board):
            print("It's a draw!")
            break

        # Computer move
        while True:
            r, c = random.randint(0,2), random.randint(0,2)
            if board[r][c] == " ":
                board[r][c] = computer
                break

        if check_winner(board, computer):
            print_board(board)
            print("Computer wins!")
            break
        if is_full(board):
            print("It's a draw!")
            break

tic_tac_toe()